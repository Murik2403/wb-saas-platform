"""Exact-file recovery retention, dry-run by default; never recursive cleanup.

Apply requires the manifest SHA256 plus independent recovery proof:
{manifest_sha256, verified_at: unix timestamp, restore_ok: true,
 erasure_guard_ok: true, independent_copy: true,
 recovery_sha256_by_namespace: {namespace: retained_recovery_sha256},
 verified_namespace_replacements: {legacy_namespace: active_namespace}}.
Replacement mapping is optional; a supplied mapping requires separately
verified data lineage and an encrypted active recovery, never a forged alias.
Proof is an operator supplied attestation from a separate restore check, not
generated by this module. Neither encryption headers nor age prove recovery.
Remote rows require externally inspected format and SHA256. Provider version
history, lock and legal holds must be explicitly verified before remote apply.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import re
import stat
import tempfile
import time

FORMATS = {"WBSAASBK1", "WBSAASBK2", "MHOFFSITE2", "SQLite3"}
SAFE_GROUP = re.compile(r"[a-z0-9][a-z0-9-]{0,63}\Z")
SAFE_FILE = re.compile(r"[a-zA-Z0-9_.-]+\Z")
HASH = re.compile(r"[0-9a-f]{64}\Z")


def _policy(days, now):
    if type(days) is not int or not 7 <= days <= 3650:
        raise ValueError("invalid_retention_days")
    if isinstance(now, bool) or not isinstance(now, (int, float)) or not math.isfinite(now) or now <= 0:
        raise ValueError("invalid_time")


def _kind(name):
    if name.endswith(".tar.gz.enc.sha256"):
        return "digest"
    if name.endswith((".tar.gz.enc", ".sqlite3.enc")) or re.fullmatch(r"[0-9a-f]{64}\.enc", name):
        return "encrypted"
    if name.endswith(".sqlite3"):
        return "sqlite"
    return "unknown"


def _reserved(parts):
    return any("quarantine" in part.lower() or "erasure-ledger" in part.lower() for part in parts)


def _parts(path, remote=False):
    if not isinstance(path, str) or "\\" in path or path.startswith("/"):
        raise ValueError("unsafe_path")
    parts = path.split("/")
    if remote and len(parts) == 3 and parts[0] == "offsite-v2":
        parts = parts[1:]
    if len(parts) != 2 or not SAFE_GROUP.fullmatch(parts[0]) or not SAFE_FILE.fullmatch(parts[1]) or parts[1] in {".", ".."} or _reserved(parts):
        raise ValueError("unsafe_path")
    return parts


def _root(value):
    path = Path(value)
    if not path.is_absolute() or any(part.is_symlink() for part in (path, *path.parents)) or not path.is_dir():
        raise ValueError("unsafe_root")
    return path.resolve()


def _hash(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _local_row(root, relative):
    root = _root(root)
    _parts(relative)
    path = root.joinpath(*relative.split("/"))
    if any(part.is_symlink() for part in (path, path.parent, root)):
        raise ValueError("unsafe_path")
    before = path.stat(follow_symlinks=False)
    directory = path.parent.stat(follow_symlinks=False)
    root_info = root.stat(follow_symlinks=False)
    if not stat.S_ISREG(before.st_mode):
        raise ValueError("not_regular_file")
    with path.open("rb") as stream:
        prefix = stream.read(16)
    kind = _kind(path.name)
    fmt = "SQLite3" if prefix.startswith(b"SQLite format 3\x00") else (
        "WBSAASBK1" if prefix.startswith(b"WBSAASBK1") else "WBSAASBK2" if prefix.startswith(b"WBSAASBK2") else "MHOFFSITE2" if prefix.startswith(b"MHOFFSITE2") else "")
    digest = _hash(path)
    after = path.stat(follow_symlinks=False)
    signature = lambda value: (value.st_size, value.st_mtime_ns, value.st_ino, value.st_dev)
    if signature(before) != signature(after):
        raise ValueError("file_changed_during_inspection")
    return {"path": relative, "namespace": relative.split("/")[0], "kind": kind,
            "format": fmt, "size": before.st_size, "mtime_ns": before.st_mtime_ns,
            "inode": before.st_ino, "device": before.st_dev, "sha256": digest,
            "namespace_inode": directory.st_ino, "namespace_device": directory.st_dev,
            "root_inode": root_info.st_ino, "root_device": root_info.st_dev}


def manifest_hash(manifest):
    body = {key: value for key, value in manifest.items() if key != "manifest_sha256"}
    return hashlib.sha256(json.dumps(body, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def _replacement_map(value):
    if value is not None and not isinstance(value, dict):
        raise ValueError("invalid_namespace_replacement")
    replacements = {} if value is None else dict(value)
    for source, target in replacements.items():
        if not isinstance(source, str) or not isinstance(target, str) or not SAFE_GROUP.fullmatch(source) or not SAFE_GROUP.fullmatch(target) or _reserved([source, target]) or source == target or target in replacements:
            raise ValueError("invalid_namespace_replacement")
    return replacements


def _creation_map(value, now):
    if value is None:
        return {}
    if not isinstance(value, dict):
        raise ValueError("invalid_creation_provenance")
    for digest, timestamp in value.items():
        if not isinstance(digest, str) or not HASH.fullmatch(digest) or type(timestamp) is not int or not 0 < timestamp <= int(now * 1e9):
            raise ValueError("invalid_creation_provenance")
    return dict(value)


def _with_creation(row, creation, now):
    # Never trust arbitrary original_created_ns fields supplied by providers.
    # Only the manifest-bound, digest-keyed provenance catalog supplies age.
    if type(row["mtime_ns"]) is not int or not 0 < row["mtime_ns"] <= int(now * 1e9):
        raise ValueError("invalid_file_timestamp")
    original = creation.get(row["sha256"])
    return {**row, "created_ns": min(row["mtime_ns"], original) if original is not None else row["mtime_ns"],
            "creation_basis": "sha256_provenance" if original is not None else "mtime_fallback"}


def _finish(rows, *, mode, root, days, now, legal_holds, excluded, namespace_replacements=None, creation_by_sha256=None):
    creation = _creation_map(creation_by_sha256, now)
    rows = [_with_creation(row, creation, now) for row in rows]
    replacements = _replacement_map(namespace_replacements)
    holds = set(legal_holds)
    for item in holds:
        if not isinstance(item, str) or not item or ".." in item.split("/"):
            raise ValueError("invalid_legal_hold")
    candidates, retained = [], []
    valid = [row for row in rows if row["size"] > 16 and (
        (row["kind"] == "encrypted" and row["format"] in {"WBSAASBK1", "WBSAASBK2", "MHOFFSITE2"})
        or (row["kind"] == "sqlite" and row["format"] == "SQLite3"))]
    namespaces = sorted({row["namespace"] for row in valid})
    newest = {group: max((row for row in valid if row["namespace"] == group),
                        key=lambda row: (row["created_ns"], row["path"])) for group in namespaces}
    for source, target in replacements.items():
        floor = newest.get(target)
        if source not in {row["namespace"] for row in rows} or floor is None or floor["kind"] != "encrypted" or target in holds or floor["path"] in holds or floor["mtime_ns"] > now * 1e9:
            raise ValueError("replacement_requires_retained_encrypted_recovery")
    cutoff = int((now - days * 86400) * 1_000_000_000)
    by_path = {row["path"]: row for row in rows}
    for row in rows:
        group = row["namespace"]
        if row["path"] in holds or group in holds:
            excluded.append({"path": row["path"], "reason": "legal_hold"})
        elif row in newest.values() and group not in replacements:
            retained.append(row)
        elif row not in valid and row["kind"] != "digest":
            excluded.append({"path": row["path"], "reason": "unverified_format"})
        elif row["created_ns"] >= cutoff:
            excluded.append({"path": row["path"], "reason": "within_window_or_future"})
        elif replacements.get(group, group) not in newest:
            excluded.append({"path": row["path"], "reason": "no_retained_recovery"})
        elif row["kind"] == "digest":
            base = row["path"][:-7]
            # Sidecars may follow their exact archive, never stand alone.
            archive = by_path.get(base)
            if archive not in valid or (archive == newest.get(group) and group not in replacements) or archive["path"] in holds or archive["created_ns"] >= cutoff or row.get("archive_sha256") != archive["sha256"]:
                excluded.append({"path": row["path"], "reason": "sidecar_not_verified_candidate"})
            else:
                candidates.append(row)
        else:
            candidates.append(row)
    result = {"version": 1, "mode": mode, "root": root, "days": days, "planned_at": now,
              "legal_holds": sorted(holds), "namespace_replacements": replacements,
              "creation_by_sha256": creation,
              "candidates": sorted(candidates, key=lambda row: row["path"]),
              "retained": sorted(retained, key=lambda row: row["path"]), "excluded": excluded}
    result["manifest_sha256"] = manifest_hash(result)
    return result


def plan_local(root, *, days=14, now=None, legal_holds=(), namespace_replacements=None, creation_by_sha256=None):
    now = time.time() if now is None else now
    _policy(days, now)
    root = _root(root)
    rows, excluded = [], []
    for group in sorted(root.iterdir()):
        if group.is_symlink() or not group.is_dir() or not SAFE_GROUP.fullmatch(group.name) or _reserved([group.name]):
            excluded.append({"path": group.name, "reason": "unsafe_or_reserved_namespace"})
            continue
        for path in sorted(group.iterdir()):
            relative = group.name + "/" + path.name
            if path.is_symlink() or not path.is_file() or _kind(path.name) == "unknown":
                excluded.append({"path": relative, "reason": "unsafe_or_unknown_file"})
                continue
            row = _local_row(root, relative)
            if row["kind"] == "digest":
                raw = path.read_text(encoding="ascii").strip().split()
                row["archive_sha256"] = raw[0] if raw and HASH.fullmatch(raw[0]) else ""
            rows.append(row)
    return _finish(rows, mode="local", root=str(root), days=days, now=now, legal_holds=legal_holds, excluded=excluded, namespace_replacements=namespace_replacements, creation_by_sha256=creation_by_sha256)


def _remote_row(item):
    parts = _parts(item["path"], remote=True)
    if not HASH.fullmatch(item.get("sha256", "")) or type(item.get("size")) is not int or item["size"] <= 0 or type(item.get("mtime_ns")) is not int or item["mtime_ns"] <= 0:
        raise ValueError("unverified_remote_metadata")
    return {"path": item["path"], "namespace": parts[0], "kind": _kind(parts[1]),
            "format": item.get("format", "") if item.get("format") in FORMATS else "", "size": item["size"], "mtime_ns": item["mtime_ns"],
            "sha256": item["sha256"], "version_id": item.get("version_id", ""),
            "archive_sha256": item.get("archive_sha256", "")}


def plan_remote(metadata, *, days=14, now=None, legal_holds=(), namespace_replacements=None, creation_by_sha256=None):
    now = time.time() if now is None else now
    _policy(days, now)
    rows, excluded, seen = [], [], set()
    for item in metadata:
        row = _remote_row(item)
        if row["path"] in seen:
            raise ValueError("duplicate_remote_path")
        seen.add(row["path"])
        rows.append(row)
    return _finish(rows, mode="remote", root=None, days=days, now=now, legal_holds=legal_holds, excluded=excluded, namespace_replacements=namespace_replacements, creation_by_sha256=creation_by_sha256)


def _authorize(manifest, acknowledgment, proof, now):
    _policy(manifest["days"], now)
    digest = manifest_hash(manifest)
    if acknowledgment != digest or manifest.get("manifest_sha256") != digest or proof.get("manifest_sha256") != digest:
        raise ValueError("manifest_acknowledgment_mismatch")
    verified = proof.get("verified_at")
    if isinstance(verified, bool) or not isinstance(verified, (int, float)) or not math.isfinite(verified) or not 0 <= now - verified <= 86400:
        raise ValueError("stale_recovery_proof")
    if any(proof.get(key) is not True for key in ("restore_ok", "erasure_guard_ok", "independent_copy")):
        raise ValueError("missing_independent_recovery_proof")
    retained = {row["namespace"]: row["sha256"] for row in manifest["retained"]}
    creation = _creation_map(manifest.get("creation_by_sha256"), manifest["planned_at"])
    for row in manifest["candidates"] + manifest["retained"]:
        if _with_creation(row, creation, manifest["planned_at"]) != row:
            raise ValueError("creation_provenance_mismatch")
    replacements = _replacement_map(manifest.get("namespace_replacements"))
    if proof.get("verified_namespace_replacements", {}) != replacements:
        raise ValueError("unverified_namespace_replacement")
    for target in replacements.values():
        if not any(row["namespace"] == target and row["kind"] == "encrypted" and row["format"] in {"WBSAASBK1", "WBSAASBK2", "MHOFFSITE2"} for row in manifest["retained"]):
            raise ValueError("replacement_requires_retained_encrypted_recovery")
    verified_hashes = proof.get("recovery_sha256_by_namespace", {})
    for row in manifest["candidates"]:
        _parts(row["path"], remote=manifest["mode"] == "remote")
        recovery_group = replacements.get(row["namespace"], row["namespace"])
        if row["kind"] not in {"encrypted", "sqlite", "digest"} or recovery_group not in retained or verified_hashes.get(recovery_group) != retained[recovery_group]:
            raise ValueError("recovery_proof_scope_mismatch")
        if row["created_ns"] >= int((manifest["planned_at"] - manifest["days"] * 86400) * 1e9) or row["path"] in manifest["legal_holds"] or row["namespace"] in manifest["legal_holds"] or any(saved["path"] == row["path"] for saved in manifest["retained"]):
            raise ValueError("ineligible_candidate")
    if len({row["path"] for row in manifest["candidates"]}) != len(manifest["candidates"]):
        raise ValueError("duplicate_candidate")


def _private_write(path, value, *, exclusive=False):
    path = Path(path)
    if any(part.is_symlink() for part in (path, *path.parents)):
        raise ValueError("unsafe_receipt_path")
    temporary = None
    if exclusive:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    else:
        fd, temporary = tempfile.mkstemp(prefix=".retention-receipt-", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            json.dump(value, stream, ensure_ascii=False, sort_keys=True)
            stream.flush()
            os.fsync(stream.fileno())
        if temporary is not None:
            os.replace(temporary, path)
            temporary = None
        if os.name != "nt":
            directory = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
            try:
                os.fsync(directory)
            finally:
                os.close(directory)
    finally:
        if temporary is not None:
            os.unlink(temporary)


def _apply(manifest, acknowledgment, proof, receipt_path, reread, delete, now):
    _authorize(manifest, acknowledgment, proof, now)
    def ensure_unchanged(row):
        try:
            equal = reread(row["path"]) == row
        except (ValueError, OSError):
            equal = False
        if not equal:
            raise ValueError("target_changed")
    # Validate whole batch before first delete, including preserved recovery.
    for row in manifest["candidates"] + manifest["retained"]:
        ensure_unchanged(row)
    receipt = {"manifest_sha256": acknowledgment, "started_at": now, "state": "started", "events": [], "deleted_count": 0}
    _private_write(receipt_path, receipt, exclusive=True)
    try:
        for row in manifest["candidates"]:
            ensure_unchanged(row)
            event = {"path": row["path"], "sha256": row["sha256"], "state": "pending", "attempted_at": time.time()}
            receipt["events"].append(event)
            # Durable intent precedes deletion, so disk failure stops mutation
            # and a crash after provider I/O leaves an auditable pending event.
            _private_write(receipt_path, receipt)
            delete(row["path"])
            event.update(state="confirmed", deleted_at=time.time())
            receipt["deleted_count"] += 1
            _private_write(receipt_path, receipt)
        receipt["state"] = "completed"
        _private_write(receipt_path, receipt)
        return receipt
    except Exception:
        receipt["state"] = "failed"
        _private_write(receipt_path, receipt)
        raise


def apply_local(manifest, *, acknowledgment, proof, receipt_path, now=None, guard=None):
    if manifest.get("mode") != "local":
        raise ValueError("wrong_manifest_mode")
    root = _root(manifest["root"])
    creation = _creation_map(manifest.get("creation_by_sha256"), manifest["planned_at"])
    def reread(relative):
        row = _local_row(root, relative)
        if row["kind"] == "digest":
            raw = root.joinpath(*relative.split("/")).read_text(encoding="ascii").strip().split()
            row["archive_sha256"] = raw[0] if raw and HASH.fullmatch(raw[0]) else ""
        return _with_creation(row, creation, manifest["planned_at"])
    def delete(relative):
        if guard is not None:guard()
        root.joinpath(*relative.split("/")).unlink()
    return _apply(manifest, acknowledgment, proof, receipt_path, reread,
                  delete, time.time() if now is None else now)


def apply_remote(manifest, *, acknowledgment, proof, receipt_path, read_metadata, delete_file, now=None):
    if manifest.get("mode") != "remote" or any(proof.get(key) is not True for key in ("versions_checked", "object_lock_checked", "legal_holds_checked")):
        raise ValueError("remote_policy_not_verified")
    creation = _creation_map(manifest.get("creation_by_sha256"), manifest["planned_at"])
    return _apply(manifest, acknowledgment, proof, receipt_path,
                  lambda path: _with_creation(_remote_row(read_metadata(path)), creation, manifest["planned_at"]), delete_file, time.time() if now is None else now)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--days", type=int, default=14)
    parser.add_argument("--legal-hold", action="append", default=[])
    parser.add_argument("--namespace-replacements", type=Path,
                        help="Explicit legacy-to-active namespace JSON; independently verify lineage before apply")
    parser.add_argument("--creation-by-sha256", type=Path,
                        help="Verified cipher-SHA256 to original creation unix-nanoseconds JSON")
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--ack")
    parser.add_argument("--proof", type=Path)
    parser.add_argument("--receipt", type=Path)
    args = parser.parse_args()
    try:
        if args.apply:
            if not args.ack or not args.proof or not args.receipt:
                raise ValueError("apply_requires_ack_proof_receipt")
            report = apply_local(json.loads(args.manifest.read_text(encoding="utf-8")), acknowledgment=args.ack,
                                 proof=json.loads(args.proof.read_text(encoding="utf-8")), receipt_path=args.receipt)
            print(json.dumps({"state": report["state"], "deleted_count": report["deleted_count"]}))
        else:
            if args.root is None:
                raise ValueError("dry_run_requires_root")
            replacements = json.loads(args.namespace_replacements.read_text(encoding="utf-8")) if args.namespace_replacements else None
            creation = json.loads(args.creation_by_sha256.read_text(encoding="utf-8")) if args.creation_by_sha256 else None
            report = plan_local(args.root, days=args.days, legal_holds=args.legal_hold, namespace_replacements=replacements, creation_by_sha256=creation)
            _private_write(args.manifest, report, exclusive=True)
            print(json.dumps({"mode": "dry_run", "manifest_sha256": report["manifest_sha256"], "candidates": len(report["candidates"])}))
        return 0
    except (ValueError, OSError, TypeError, KeyError):
        print(json.dumps({"error": "retention_operation_failed"}))
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
